#! /usr/bin/env dart

import 'dart:io'
    show Directory, File, InternetAddressType, NetworkInterface, exit, stderr;

import 'package:yaml/yaml.dart';

Never _exitWithError(String message) {
  stderr.writeln(message);
  exit(1);
}

/// Finds the first non-loopback IPv4 address associated with the machine.
Future<String?> getLocalIpAddress() async {
  try {
    final interfaces = await NetworkInterface.list(
      type: InternetAddressType.IPv4,
    );
    for (final interface in interfaces) {
      for (final address in interface.addresses) {
        if (address.type == InternetAddressType.IPv4 && !address.isLoopback) {
          return address.address;
        }
      }
    }
  } on Object catch (error) {
    stderr.writeln('Warning: Could not get local IP address: $error');
  }

  return null;
}

/// Reads a value from `openbudget_server/config/<environment>.yaml`.
T _getConfigValue<T extends Object>(String environment, List<String> keys) {
  final configPath = 'openbudget_server/config/$environment.yaml';
  final configFile = File(configPath);

  if (!configFile.existsSync()) {
    _exitWithError('Error: Configuration file not found at $configPath');
  }

  try {
    final configContent = configFile.readAsStringSync();
    var currentValue = loadYaml(configContent) as Object?;

    for (final key in keys) {
      if (currentValue is YamlMap && currentValue.containsKey(key)) {
        currentValue = currentValue[key] as Object?;
      } else {
        _exitWithError(
          'Error: Key "$key" not found in path ${keys.join('.')} in $configPath',
        );
      }
    }

    if (currentValue is T) {
      return currentValue;
    }

    _exitWithError(
      'Error: Value at ${keys.join('.')} in $configPath is not a $T',
    );
  } on Object catch (error) {
    _exitWithError('Error reading or parsing $configPath: $error');
  }
}

Future<void> main(List<String> arguments) async {
  var environment = 'development';
  if (arguments.isNotEmpty) {
    final providedEnv = arguments[0].toLowerCase();
    if (['development', 'staging', 'production'].contains(providedEnv)) {
      environment = providedEnv;
    } else {
      stderr
        ..writeln('Invalid environment specified: ${arguments[0]}')
        ..writeln(
          'Usage: dart run openbudget_scripts:update_dev_server_url '
          '[development|staging|production]',
        )
        ..writeln('Defaulting to development.');
    }
  }

  late final String clientUrl;
  try {
    if (environment == 'development') {
      final localIp = await getLocalIpAddress();
      final devPort = _getConfigValue<int>(environment, [
        'apiServer',
        'publicPort',
      ]);

      if (localIp != null) {
        clientUrl = 'http://$localIp:$devPort/';
      } else {
        stderr.writeln(
          'Local IP not found; falling back to publicHost in development config.',
        );
        final devHost = _getConfigValue<String>(environment, [
          'apiServer',
          'publicHost',
        ]);
        clientUrl = 'http://$devHost:$devPort/';
      }
    } else {
      final publicHost = _getConfigValue<String>(environment, [
        'apiServer',
        'publicHost',
      ]);
      final publicPort = _getConfigValue<int>(environment, [
        'apiServer',
        'publicPort',
      ]);
      clientUrl = publicPort == 443
          ? 'https://$publicHost/'
          : 'https://$publicHost:$publicPort/';
    }
  } on Object catch (error) {
    _exitWithError('Error processing configuration for $environment: $error');
  }

  const envFilePath = '.tmp/flutter.env';
  final envFile = File(envFilePath);
  final envContent =
      '# Generated by openbudget_scripts:update_dev_server_url\n'
      'OPENBUDGET_API_URL="$clientUrl"\n';

  try {
    Directory('.tmp').createSync(recursive: true);
    envFile.writeAsStringSync(envContent);
    stderr.writeln(
      'Updated $envFilePath with OPENBUDGET_API_URL="$clientUrl" '
      'for $environment environment.',
    );
  } on Object catch (error) {
    _exitWithError('Failed to write to $envFilePath: $error');
  }
}
